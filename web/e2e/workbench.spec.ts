import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test('edits runs compares and exports a backtest', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => { errors.push(error.message); console.log(`Browser error: ${error.message}`) })
  await page.goto('/datasets')
  await expect(page.getByRole('heading', { name: '数据版本', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '生成演示', exact: true }).click()
  await expect(page.getByText(/已验证并登记数据版本/)).toBeVisible({ timeout: 60_000 })
  await page.getByRole('link', { name: '策略与实验', exact: true }).click()
  await page.getByRole('combobox', { name: '选择数据', exact: true }).selectOption({ index: 1 })
  const strategies = page.getByRole('combobox', { name: '选择策略', exact: true })
  await strategies.selectOption({ label: await strategies.locator('option').filter({ hasText: 'buy_hold' }).innerText() })
  const editor = page.locator('.cm-content[contenteditable="true"]')
  await expect(editor).toContainText('create_strategy')
  await editor.fill('from quanto.strategies.base import Hold, TargetPortfolio\n\nclass Demo:\n    warmup_bars = 0\n    def __init__(self, params):\n        self.weight = params["weight"]\n        self.done = False\n    def should_evaluate(self, ctx):\n        return not self.done\n    def on_close(self, ctx):\n        self.done = True\n        symbol = sorted(ctx.eligible_symbols)[0]\n        return TargetPortfolio({symbol: self.weight}, {symbol: "演示持有"}, {})\n\ndef create_strategy(params):\n    return Demo(params)\n')
  await page.getByRole('button', { name: 'strategy.json', exact: true }).click()
  await editor.fill(JSON.stringify({ name: '浏览器演示', entrypoint: 'strategy.py:create_strategy', parameter_schema: { type: 'object', properties: { weight: { type: 'number', title: '目标权重', minimum: 0, maximum: 1, default: 0.5 } }, additionalProperties: false }, required_data_columns: ['date', 'symbol', 'close'], auxiliary_sources: [], research_data: [] }, null, 2))
  await page.getByRole('button', { name: '保存新修订', exact: true }).click()
  await expect(page.getByLabel('目标权重', { exact: true })).toBeVisible()
  await page.getByLabel('目标权重', { exact: true }).fill('0.5')
  await page.getByLabel('样本用途').fill('演示流程验收')
  await page.getByLabel('绩效起始日').fill('2018-01-02')
  await page.getByLabel('结束日', { exact: true }).fill('2018-01-31')
  await page.getByLabel('初始资金').fill('100000')
  await page.getByLabel('证券代码（逗号分隔）').fill('512480')
  await page.getByRole('button', { name: '保存实验', exact: true }).click()
  await expect(page.getByText('已保存实验修订 1')).toBeVisible()
  const experiment = await page.getByRole('combobox', { name: '实验草稿', exact: true }).inputValue()

  async function run(draftId: string) {
    await page.getByRole('link', { name: '回测任务', exact: true }).click()
    await expect(page.getByRole('heading', { name: '回测任务', exact: true })).toBeVisible()
    await page.getByRole('combobox', { name: '实验草稿', exact: true }).selectOption(draftId)
    const created = page.waitForResponse(response => response.url().endsWith('/api/runs') && response.request().method() === 'POST')
    await page.getByRole('button', { name: '运行', exact: true }).click()
    const response = await created
    expect(response.ok()).toBeTruthy()
    const record = await response.json()
    await page.goto(`/runs/${record.run_id}`)
    await expect(page.getByRole('heading', { name: '最终绩效', exact: true })).toBeVisible({ timeout: 60_000 })
    return record.run_id as string
  }
  const first = await run(experiment)
  const detailRequests: string[] = []
  const recordDetailRequest = (request: import('@playwright/test').Request) => {
    if (request.url().includes(`/api/runs/${first}/`)) detailRequests.push(request.url())
  }
  page.on('request', recordDetailRequest)
  await page.reload()
  await expect(page.getByRole('heading', { name: '最终绩效', exact: true })).toBeVisible()
  await expect(page.getByRole('cell', { name: '2018-01-31', exact: true })).toBeVisible()
  expect(detailRequests.filter(url => url.includes('/tables/'))).toHaveLength(5)
  expect(detailRequests.some(url => url.includes('/tables/positions'))).toBe(false)
  expect(detailRequests.filter(url => url.includes('/charts/'))).toHaveLength(1)
  expect(detailRequests.filter(url => url.includes('/tables/')).every(url => url.includes('limit=100') && (url.includes('date_from=') || url.includes('context_date=')))).toBe(true)
  page.off('request', recordDetailRequest)
  await page.getByRole('button', { name: '全区间', exact: true }).click()
  await page.getByRole('tab', { name: '订单', exact: true }).click()
  await expect(page.locator('.table-wrap').filter({ has: page.getByRole('columnheader', { name: '委托数量', exact: true }) })).toContainText('512480')
  const chart = page.locator('.result-chart').first()
  const started = Date.now()
  await chart.scrollIntoViewIfNeeded()
  await expect(chart.locator('svg')).toBeVisible()
  const legend = await chart.locator('svg text').filter({ hasText: /^策略净值$/ }).boundingBox()
  const lastDate = await chart.locator('svg text').filter({ hasText: /^2018-01-31$/ }).boundingBox()
  expect(legend).not.toBeNull()
  expect(lastDate).not.toBeNull()
  expect(legend!.y + legend!.height < lastDate!.y || legend!.y > lastDate!.y + lastDate!.height).toBeTruthy()
  testInfo.annotations.push({ type: 'first-chart-ms', description: String(Date.now() - started) })
  await page.screenshot({ path: testInfo.outputPath('desktop-chart.png') })
  await page.getByLabel('图表起始日', { exact: true }).fill('2018-01-10')
  await page.getByLabel('图表结束日', { exact: true }).fill('2018-01-20')
  const rangedChart = page.waitForResponse(response => response.url().includes(`/api/runs/${first}/charts/curves?`) && response.url().includes('date_from=2018-01-10') && response.url().includes('date_to=2018-01-20'))
  await page.getByRole('button', { name: '更新图表', exact: true }).click()
  const chartData = await (await rangedChart).json()
  expect(chartData.items.length).toBeGreaterThan(0)
  expect(chartData.items.every((row: { date: string }) => row.date >= '2018-01-10' && row.date <= '2018-01-20')).toBe(true)
  await expect(page.getByLabel('图表起始日', { exact: true })).toHaveValue('2018-01-10')
  await expect(page.getByLabel('图表结束日', { exact: true })).toHaveValue('2018-01-20')
  await page.reload()
  await expect(page.getByRole('heading', { name: '最终绩效', exact: true })).toBeVisible()
  await page.getByRole('link', { name: '策略与实验', exact: true }).click()
  await page.getByRole('combobox', { name: '实验草稿', exact: true }).selectOption(experiment)
  await page.getByLabel('目标权重', { exact: true }).fill('0.9')
  await page.getByLabel('样本用途', { exact: true }).fill('later mutable purpose')
  await page.getByRole('button', { name: '保存实验', exact: true }).click()
  await expect(page.getByText('已保存实验修订 2')).toBeVisible()
  await page.goto(`/runs/${first}`)
  await expect(page.getByText(/演示数据：合成绩效/).first()).toBeVisible()
  await page.getByRole('button', { name: '从此历史运行创建实验' }).click()
  await expect(page.getByRole('heading', { name: '策略与实验', exact: true })).toBeVisible()
  await expect(page.getByLabel('目标权重', { exact: true })).toHaveValue('0.5')
  await expect(page.getByLabel('样本用途', { exact: true })).not.toHaveValue('later mutable purpose')
  await page.getByLabel('目标权重', { exact: true }).fill('0.7')
  await page.getByRole('button', { name: '保存实验', exact: true }).click()
  await expect(page.getByText('已保存实验修订 2')).toBeVisible()
  const cloned = await page.getByRole('combobox', { name: '实验草稿', exact: true }).inputValue()
  expect(cloned).not.toBe(experiment)
  const second = await run(cloned)
  await expect(page.getByText(/演示数据：合成绩效/).first()).toBeVisible()
  await page.getByText('查看冻结输入与来源').click()
  await expect(page.locator('pre').filter({ hasText: 'source_run_id' }).first()).toContainText(first)
  await page.getByLabel('模拟日期', { exact: true }).fill('2018-01-02')
  await page.getByRole('button', { name: '查询追踪', exact: true }).click()
  await expect(page.getByText(/策略原始目标权重/).first()).toBeVisible()
  await expect(page.getByText(/风控批准目标权重/).first()).toBeVisible()
  await page.getByRole('link', { name: '对比', exact: true }).click()
  await page.getByLabel('运行 ID（每行一个）').fill(`${first}\n${second}`)
  await page.getByRole('button', { name: '比较运行', exact: true }).click()
  await expect(page.getByRole('heading', { name: '可比运行曲线' })).toBeVisible()
  await expect(page.getByText(/演示数据：合成绩效/).first()).toBeVisible()
  await expect(page.getByText('0.7', { exact: false }).first()).toBeVisible()
  await page.goto(`/runs/${second}`)
  const downloading = page.waitForEvent('download')
  await page.getByRole('button', { name: '独立 HTML', exact: true }).click()
  const download = await downloading
  const file = testInfo.outputPath(download.suggestedFilename())
  await download.saveAs(file)
  const html = await readFile(file, 'utf8')
  expect(html).toContain('adjusted_research')
  expect(html).toContain('演示数据：合成绩效，不代表真实市场表现')
  expect(html).toContain('is_demo')
  await page.goto('/runs/missing')
  await expect(page.getByRole('alert')).toContainText('NOT_FOUND')
  await page.screenshot({ path: testInfo.outputPath('desktop-error.png') })
  expect(errors).toEqual([])
  testInfo.annotations.push({ type: 'runs', description: `${first},${second}` })
})
